import type { Activity, ActivityLevel, QuizQuestionItem } from '@/types/activity'
import { pickThumbnail } from './thumbnails.ts'

type Diff = 'advanced' | 'intermediate' | 'basic'

function base(
  partial: Omit<Activity, 'isPublished' | 'isSystem' | 'points' | 'difficulty'> & {
    points?: number
    diff: Diff
  },
): Activity {
  const { diff, points: customPoints, ...rest } = partial
  const points =
    customPoints ?? (diff === 'advanced' ? 20 : diff === 'intermediate' ? 15 : 10)
  return {
    ...rest,
    difficulty: diff,
    points,
    isPublished: true,
    isSystem: true,
  }
}

function q(
  question: string,
  options: [string, string, string, string],
  correctIndex: number,
  explanation?: string,
): QuizQuestionItem {
  return { question, options, correctIndex, explanation }
}

